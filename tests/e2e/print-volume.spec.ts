import { openApplicationMenuItem } from "./application-menu-support"
import { saved } from "./authored-parts-ui-support"
import { expect, test } from "./fixtures"
import { invokeModelCommand } from "./model-command-support"

test("checks current CAD placement and a rotated print copy against a persistent printer profile", async ({
  page,
}) => {
  await page.goto("/")
  await expect(page.getByText("Saved in this browser", { exact: true })).toBeVisible()
  await openApplicationMenuItem(page, "Settings…")
  const settings = page.getByRole("dialog", { name: "Settings", exact: true })
  await settings.getByLabel("Bed width X (mm)").fill("30")
  await settings.getByLabel("Bed depth Y (mm)").fill("30")
  await settings.getByLabel("Maximum print height Z (mm)").fill("25")
  await settings.getByRole("button", { name: "Apply printer profile" }).click()
  await expect(settings.getByLabel("Show printer bed and height envelope")).toBeChecked()
  await settings.getByRole("button", { name: "Done", exact: true }).click()
  const toolbar = page.getByRole("toolbar", { name: "Model commands" })
  await invokeModelCommand(page, "Primitives", "Box")
  const box = page.getByRole("form", { name: "Create box" })
  await box.getByRole("combobox", { name: "Width", exact: true }).fill("40 mm")
  await box.getByRole("combobox", { name: "Depth", exact: true }).fill("20 mm")
  await box.getByRole("combobox", { name: "Height", exact: true }).fill("30 mm")
  await box.getByRole("button", { name: "Create box", exact: true }).click()
  const viewport = page.getByRole("region", { name: "3D viewport" })
  await expect(viewport.getByText("Outside the build volume in this orientation")).toBeVisible()
  await expect(viewport.getByText("Z upper boundary: exceeds by 5.00 mm")).toBeVisible()
  await saved(page)
  await page.reload()
  await expect(viewport.getByText("Custom printer: 30 × 30 × 25 mm")).toBeVisible()
  await page.screenshot({ path: test.info().outputPath("main-print-bed.png") })
  await expect(toolbar.getByRole("button", { name: "Undo", exact: true })).toBeDisabled()
  await openApplicationMenuItem(page, "Export geometry…")
  const exportDialog = page.getByRole("dialog", { name: "Export model" })
  await exportDialog.getByRole("button", { name: "Prepare print / breakaway fins…" }).click()
  await exportDialog.getByLabel("Tilt around X (degrees)").fill("0")
  await exportDialog.getByLabel("Generate experimental breakaway fins").uncheck()
  await exportDialog.getByRole("button", { name: "Generate print preview" }).click()
  await expect(exportDialog.getByText("X upper boundary: exceeds by 5.00 mm")).toBeVisible()
  await expect(exportDialog.getByText("X lower boundary: exceeds by 5.00 mm")).toBeVisible()
  await exportDialog.getByLabel("Rotate on bed around Z (degrees)").fill("90")
  await expect(
    exportDialog.getByRole("button", { name: "Download prepared 3MF" }),
  ).not.toBeVisible()
  await exportDialog.getByRole("button", { name: "Generate print preview" }).click()
  await expect(exportDialog.getByText("Y upper boundary: exceeds by 5.00 mm")).toBeVisible()
  await expect(exportDialog.getByText("X upper boundary: exceeds by 5.00 mm")).not.toBeVisible()
  await expect(exportDialog.getByText(/1 body · 0 fins/)).toBeVisible()
  await exportDialog.getByRole("button", { name: "Fit preview", exact: true }).click()
  await page.screenshot({ path: test.info().outputPath("print-bed-dark.png") })
  await page.locator("html").evaluate((element) => element.classList.remove("dark"))
  await page.screenshot({ path: test.info().outputPath("print-bed-light.png") })
  const printCanvas = exportDialog.getByLabel("Prepared print model and breakaway fins")
  const area = await printCanvas.boundingBox()
  if (!area) throw new Error("Print preview canvas has no bounds.")
  await printCanvas.click({ position: { x: area.width / 2, y: area.height * 0.32 } })
  const layFace = exportDialog.getByRole("button", { name: "Lay selected face on bed" })
  await expect(layFace).toBeEnabled()
  await layFace.click()
  await expect(exportDialog.getByLabel("Rotate on bed around Z (degrees)")).toHaveValue("0")
  await expect(
    exportDialog.getByText("Prepared bounds: 40.00 × 20.00 × 30.00 mm.", { exact: false }),
  ).toBeVisible()

  await exportDialog.getByRole("button", { name: "Close", exact: true }).click()
  await expect(page.getByRole("button", { name: "Actions for Box 1" })).toBeVisible()
  await expect(toolbar.getByRole("button", { name: "Undo", exact: true })).toBeDisabled()
  await expect(viewport).toHaveAttribute("data-rendered-feature-count", "1")
  await page.getByRole("treeitem", { name: "Box 1", exact: true }).click()
  const original = page.getByRole("form", { name: "Edit box" })
  await expect(original.getByRole("combobox", { name: "Width", exact: true })).toHaveValue("40 mm")
  await expect(original.getByRole("combobox", { name: "Depth", exact: true })).toHaveValue("20 mm")
  await expect(original.getByRole("combobox", { name: "Height", exact: true })).toHaveValue("30 mm")
})
