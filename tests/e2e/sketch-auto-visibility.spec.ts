import { expect, test } from "./fixtures"
import { confirmSketchPlane, drawRectangle } from "./sketch-helpers"

test("auto hides a successful extrusion profile and preserves manual visibility through edits and reopen", async ({
  page,
}) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("/")
  const saved = page.getByText("Saved in this browser", { exact: true })
  await expect(saved).toBeVisible({ timeout: 30000 })
  const commands = page.getByRole("toolbar", { name: "Model commands" })
  await commands.getByRole("button", { name: "Create sketch", exact: true }).click()
  await confirmSketchPlane(page, "xy")
  await drawRectangle(page)
  await commands.getByRole("button", { name: "Extrude", exact: true }).click()
  const form = page.getByRole("form", { name: "Extrude profile", exact: true })
  const viewport = page.getByRole("region", { name: "3D viewport" })
  await expect(viewport).toHaveAttribute("data-preview-status", "ready", { timeout: 30000 })
  await form.getByRole("button", { name: "Create extrusion", exact: true }).click()
  await expect(saved).toBeVisible({ timeout: 30000 })
  const show = page.getByRole("button", { name: "Show Sketch 1", exact: true })
  const hide = page.getByRole("button", { name: "Hide Sketch 1", exact: true })
  await expect(show).toBeVisible()
  await expect(viewport).toHaveAttribute("data-rendered-sketch-count", "0")
  await commands.getByRole("button", { name: "Undo", exact: true }).click()
  await expect(page.getByRole("treeitem", { name: "Extrusion 1", exact: true })).toHaveCount(0)
  await expect(hide).toBeVisible()
  await commands.getByRole("button", { name: "Redo", exact: true }).click()
  await expect(page.getByRole("treeitem", { name: "Extrusion 1", exact: true })).toBeVisible()
  await expect(show).toBeVisible()
  await page.getByRole("treeitem", { name: "Sketch 1", exact: true }).click()
  await expect(page.getByRole("img", { name: "Editable sketch geometry" })).toBeVisible()
  await page.getByRole("button", { name: "Finish sketch", exact: true }).click()
  await expect(show).toBeVisible()
  await expect(viewport).toHaveAttribute("data-rendered-sketch-count", "0")
  await show.click()
  await expect(hide).toBeVisible()
  await page.getByRole("treeitem", { name: "Extrusion 1", exact: true }).click()
  const edit = page.getByRole("form", { name: "Edit extrusion", exact: true })
  await edit.getByRole("combobox", { name: "Distance", exact: true }).fill("15 mm")
  await expect(viewport).toHaveAttribute("data-preview-status", "ready", { timeout: 30000 })
  await edit.getByRole("button", { name: "Update extrusion", exact: true }).click()
  await expect(saved).toBeVisible({ timeout: 30000 })
  await expect(hide).toBeVisible()
  await expect(viewport).toHaveAttribute("data-rendered-sketch-count", "1")
  await page.reload()
  await expect(saved).toBeVisible({ timeout: 30000 })
  await expect(hide).toBeVisible()
  await expect(viewport).toHaveAttribute("data-rendered-sketch-count", "1")
})
