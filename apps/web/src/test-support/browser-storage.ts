/** Browser storage substitute for jsdom tests when Node provides its own global storage. */
export function createTestBrowserStorage(): Storage {
  const entries = new Map<string, string>()
  return {
    clear: () => entries.clear(),
    getItem: (key) => entries.get(key) ?? null,
    key: (index) => [...entries.keys()][index] ?? null,
    get length() {
      return entries.size
    },
    removeItem: (key) => {
      entries.delete(key)
    },
    setItem: (key, value) => {
      entries.set(key, value)
    },
  }
}
