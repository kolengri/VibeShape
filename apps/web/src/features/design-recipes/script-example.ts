/** Self-contained TypeScript: no imports or ambient host API are needed. */
export const designScriptExample = `// Three independent spheres generated by a typed loop.
const mm = (value: number) => ({
  schemaVersion: 0, dimension: "length", value, unit: "mm",
  source: { value, unit: "mm", expression: null },
});
const recipe = {
  format: "vibeshape.recipe", version: 1, name: "Sphere family",
  displayUnits: { length: "mm", angle: "deg" },
  variables: [], sketches: [], features: [], history: [],
};
for (let index: number = 0; index < 3; index++) {
  const id = "0195b5ac-b250-7a2c-8c33-" + String(index + 1).padStart(12, "0");
  recipe.features.push({
    schemaVersion: 1, id, label: "Sphere " + (index + 1),
    type: {
      moduleId: "org.vibeshape.core.part-design", moduleVersion: "0.1.0",
      typeId: "org.vibeshape.feature.part-design.sphere", schemaVersion: 1,
    },
    parameters: { radius: mm(Math.sqrt(9)), origin: { x: mm(index * 15), y: mm(0), z: mm(3) } },
    dependencies: [], references: [], semanticInputs: [], suppressed: false,
  });
  recipe.history.push({ kind: "feature", id });
}
export default recipe;
`
